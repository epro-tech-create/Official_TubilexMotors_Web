BEGIN;
CREATE TABLE IF NOT EXISTS media (
  id uuid PRIMARY KEY, data bytea NOT NULL,
  content_type text NOT NULL DEFAULT 'image/webp',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS vehicles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug varchar(150) UNIQUE NOT NULL, name varchar(100) NOT NULL,
  category varchar(30) NOT NULL CHECK (category IN ('SUV','Sedan','Pickup','Luxury','Hatchback')),
  description text NOT NULL, image text NOT NULL,
  price bigint CHECK (price >= 0), year integer CHECK (year >= 1900), mileage integer CHECK (mileage >= 0),
  fuel varchar(30) NOT NULL DEFAULT 'Not specified', transmission varchar(30) NOT NULL DEFAULT 'Not specified',
  status varchar(20) NOT NULL DEFAULT 'available' CHECK (status IN ('available','reserved','sold')),
  featured boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS vehicles_status_category ON vehicles (status, category);
CREATE TABLE IF NOT EXISTS enquiries (
  id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL, email varchar(254) NOT NULL, phone varchar(30) NOT NULL DEFAULT '',
  message text NOT NULL, vehicle_id integer REFERENCES vehicles(id) ON DELETE SET NULL,
  status varchar(20) NOT NULL DEFAULT 'new' CHECK (status IN ('new','contacted','closed')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS enquiries_created_at ON enquiries (created_at DESC);
CREATE TABLE IF NOT EXISTS enquiry_limits (key text PRIMARY KEY, count integer NOT NULL, window_start timestamptz NOT NULL);
-- Better Auth's built-in PostgreSQL adapter tables.
CREATE TABLE IF NOT EXISTS "user" (
  id text PRIMARY KEY, name text NOT NULL, email text UNIQUE NOT NULL,
  "emailVerified" boolean NOT NULL DEFAULT false, image text,
  "createdAt" timestamptz NOT NULL DEFAULT now(), "updatedAt" timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS session (
  id text PRIMARY KEY, "expiresAt" timestamptz NOT NULL, token text UNIQUE NOT NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now(), "updatedAt" timestamptz NOT NULL DEFAULT now(),
  "ipAddress" text, "userAgent" text, "userId" text NOT NULL REFERENCES "user"(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS session_user_id_idx ON session ("userId");
CREATE TABLE IF NOT EXISTS account (
  id text PRIMARY KEY, "accountId" text NOT NULL, "providerId" text NOT NULL,
  "userId" text NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
  "accessToken" text, "refreshToken" text, "idToken" text,
  "accessTokenExpiresAt" timestamptz, "refreshTokenExpiresAt" timestamptz,
  scope text, password text, "createdAt" timestamptz NOT NULL DEFAULT now(), "updatedAt" timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS account_user ON account ("userId");
CREATE TABLE IF NOT EXISTS verification (
  id text PRIMARY KEY, identifier text NOT NULL, value text NOT NULL,
  "expiresAt" timestamptz NOT NULL, "createdAt" timestamptz NOT NULL DEFAULT now(), "updatedAt" timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS "rateLimit" (id text PRIMARY KEY, key text UNIQUE NOT NULL, count integer NOT NULL, "lastRequest" bigint NOT NULL);
CREATE TABLE IF NOT EXISTS admin_users (user_id text PRIMARY KEY REFERENCES "user"(id) ON DELETE CASCADE);
COMMIT;
